"""Detexify's training data (http://detexify.kirelabs.org), licensed under the ODbL 1.0.

The dump is a PostgreSQL table ``samples(id, key, strokes)``. ``key`` names a LaTeX symbol
(``<package>-<encoding>-_<command>``) and ``strokes`` is JSON ``[[[x, y, t], ...], ...]``
in canvas pixels (y down) with millisecond timestamps.

The data has no writer ids. The UTC day of a sample's first timestamp serves as a
pseudo-writer, so the train/test split keeps each day (and therefore almost every drawing
session) on one side. See DECISIONS.md.

``resources/detexify_unicode.tsv`` maps each key to a code point. It was generated by
``glyphsketch.tools.detexify_mapping`` from W3C's unicode.xml plus hand-checked entries.
"""

