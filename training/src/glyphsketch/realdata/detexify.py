@dataclass(frozen=True)
class DetexifyRecord:
    sample_id: int
    key: str
    strokes: list[np.ndarray]
    first_timestamp_ms: int | None


def parse_dump(path: Path) -> Iterator[DetexifyRecord]:
    """Yield every sample of the ``COPY samples (id, key, strokes)`` block of the dump."""
    opener = gzip.open if path.name.endswith(".gz") else open
    with opener(path, "rt", encoding="utf-8") as stream:
        in_copy_block = False
        for line in stream:
            if not in_copy_block:
                in_copy_block = line.startswith("COPY samples (id, key, strokes)")
                continue
            if line.startswith("\\."):
                return
            sample_id, key, strokes_json = line.rstrip("\n").split("\t")
            raw_strokes = json.loads(strokes_json)
            strokes = [
                np.array([[point[0], point[1]] for point in stroke], dtype=np.float32)
                for stroke in raw_strokes
                if stroke
            ]
            first_timestamp = None
            if raw_strokes and raw_strokes[0] and len(raw_strokes[0][0]) > 2:
                first_timestamp = int(raw_strokes[0][0][2])
            yield DetexifyRecord(int(sample_id), key, strokes, first_timestamp)


def pseudo_writer(first_timestamp_ms: int | None) -> str:
    if first_timestamp_ms is None:
        return "day-unknown"
    day = datetime.fromtimestamp(first_timestamp_ms / 1000, UTC).date()
    return f"day-{day.isoformat()}"


@dataclass(frozen=True)
class MappingEntry:
    key: str
    command: str
    code_point: int | None
    source: str
    note: str


def load_mapping(path: Path = MAPPING_PATH) -> dict[str, MappingEntry]:
    entries: dict[str, MappingEntry] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        key, command, code_point, source, note = (line.split("\t") + [""] * 5)[:5]
        entries[key] = MappingEntry(
            key=key,
            command=command,
            code_point=parse_code_point(code_point) if code_point else None,
            source=source,
            note=note,
        )
    return entries


def detexify_samples(
    dump_path: Path, mapping: dict[str, MappingEntry], allowed_code_points: set[int]
) -> Iterator[DrawingSample]:
    """Samples whose key maps to a code point in ``allowed_code_points``."""
    for record in parse_dump(dump_path):
        entry = mapping.get(record.key)
        if entry is None or entry.code_point not in allowed_code_points or not record.strokes:
            continue
        yield DrawingSample(
            dataset=DATASET_NAME,
            sample_id=str(record.sample_id),
            writer=pseudo_writer(record.first_timestamp_ms),
            label=record.key,
            code_point=entry.code_point,
            strokes=record.strokes,
        )
